-- 027：报表任务记录视觉模板标识（覆盖 23.15）。
--
-- 背景：报表需要多套视觉模板供用户选择。模板只影响呈现，不影响取数、授权、
-- 配额与成本，因此**不进 ReportPlan、不进 canonical_hash**——否则改一次配色
-- 就要重新预览（一次 LLM 调用）并重新确认。
--
-- 语义边界：
--   * 载体是 Job 而不是 Plan：模板在创建任务时选定，发布时写入页面文档的 theme；
--   * 列可空：为空表示使用前端默认模板，历史任务同样适用；
--   * 不做清单校验：模板清单在前端注册表，后端再存一份必然脱钩；
--     应用层只校验格式 ^[a-z0-9_-]{1,32}$。

ALTER TABLE report_jobs ADD COLUMN IF NOT EXISTS template_id VARCHAR(32);
