-- 028：报表任务记录预览凭证哈希（覆盖 23.20）。
--
-- 背景：用户在预览页可以取消计划期的发散单元。裁剪只能删减、不能新增，因此
-- 不构成越权；但裁剪后有效计划的哈希与客户端持有的预览凭证哈希不同，需要分列记录。
--
-- 语义边界：
--   * plan_hash 仍是 plan_json 的校验和（写入时现算），语义不变；
--   * preview_hash 是客户端提交的预览凭证，用于审计「这份计划来自哪次预览」；
--   * 未裁剪时两者相等；
--   * 列可空：本迁移之前创建的历史任务没有预览凭证。

ALTER TABLE report_jobs ADD COLUMN IF NOT EXISTS preview_hash VARCHAR(80);
